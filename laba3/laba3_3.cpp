#include <iostream>
#include <cmath>
using namespace std;

int main() {
    double x, y;
    cout << "Введіть координату x: ";
    cin >> x;
    cout << "Введіть координату y: ";
    cin >> y;

    // Область: трикутник у верхній півплощині z вершинами (-1,0), (1,0), (0,1)
    // Математична умова: |x| + |y| <= 1 та y >= 0
    if ((abs(x) + abs(y) <= 1) && (y >= 0)) {
        cout << "Точка (" << x << ", " << y << ") попадає в заштриховану область." << endl;
    } else {
        cout << "Точка (" << x << ", " << y << ") НЕ попадає в заштриховану область." << endl;
    }

    return 0;
}